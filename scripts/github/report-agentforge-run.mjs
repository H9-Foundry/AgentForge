import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";

function requireEnv(name) {
  const value = process.env[name];
  if (!value) {
    throw new Error(`Missing required environment variable: ${name}`);
  }
  return value;
}

function gh(args) {
  const result = spawnSync("gh", args, {
    encoding: "utf8",
    env: process.env
  });

  if (result.status !== 0) {
    throw new Error(result.stderr || result.stdout || `gh ${args.join(" ")} failed`);
  }

  return result.stdout.trim();
}

function ghJson(args) {
  return JSON.parse(gh(args));
}

function blockedActions(entries) {
  return entries.reduce((total, entry) => total + entry.blockedActions.length, 0);
}

function blockedPlugins(bundle) {
  return Array.isArray(bundle.blockedPlugins) ? bundle.blockedPlugins.length : 0;
}

function buildRunSummary(workflowName, bundle, runUrl) {
  const lines = [
    `## AgentForge \`${workflowName}\` report`,
    "",
    `- Run ID: \`${bundle.runId}\``,
    `- Status: \`${bundle.status}\``,
    `- Findings: ${bundle.findings.length}`,
    `- Blocked actions: ${blockedActions(bundle.entries)}`,
    `- Blocked plugins: ${blockedPlugins(bundle)}`
  ];

  if (runUrl) {
    lines.push(`- Workflow run: ${runUrl}`);
  }

  lines.push("");

  if (bundle.findings.length > 0) {
    lines.push("### Findings", "");
    for (const finding of bundle.findings.slice(0, 10)) {
      lines.push(`- [${finding.severity}] ${finding.title}: ${finding.summary}`);
    }
    lines.push("");
  }

  if (blockedActions(bundle.entries) > 0) {
    lines.push("### Blocked Actions", "");
    for (const entry of bundle.entries.filter((candidate) => candidate.blockedActions.length > 0)) {
      lines.push(`- ${entry.nodeName}: ${entry.blockedActions.join(", ")}`);
    }
    lines.push("");
  }

  if (blockedPlugins(bundle) > 0) {
    lines.push("### Blocked Plugins", "");
    for (const plugin of bundle.blockedPlugins) {
      lines.push(`- ${plugin.name} (${plugin.package}): ${plugin.reason}`);
    }
    lines.push("");
  }

  lines.push("_Generated by AgentForge GitHub Action._");
  return lines.join("\n");
}

function buildTrackerComment(workflowName, bundle, runUrl) {
  return [
    `Phase update from \`${workflowName}\`.`,
    "",
    `- Run ID: \`${bundle.runId}\``,
    `- Status: \`${bundle.status}\``,
    `- Findings: ${bundle.findings.length}`,
    `- Blocked actions: ${blockedActions(bundle.entries)}`,
    `- Blocked plugins: ${blockedPlugins(bundle)}`,
    runUrl ? `- Workflow run: ${runUrl}` : null,
    "",
    "The latest JSON and markdown audit artifacts were uploaded with this workflow run."
  ]
    .filter(Boolean)
    .join("\n");
}

function upsertIssueComment(repo, issueNumber, marker, body) {
  const comments = ghJson(["api", `repos/${repo}/issues/${issueNumber}/comments`]);
  const existing = comments.find((comment) => typeof comment.body === "string" && comment.body.includes(marker));

  if (existing) {
    gh(["api", `repos/${repo}/issues/comments/${existing.id}`, "--method", "PATCH", "-f", `body=${body}`]);
    return;
  }

  gh(["api", `repos/${repo}/issues/${issueNumber}/comments`, "--method", "POST", "-f", `body=${body}`]);
}

const bundlePath = requireEnv("AGENTFORGE_BUNDLE_PATH");
const workflowName = process.env.AGENTFORGE_WORKFLOW_NAME ?? "pr-review";
const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
const runUrl =
  process.env.GITHUB_SERVER_URL && process.env.GITHUB_REPOSITORY && process.env.GITHUB_RUN_ID
    ? `${process.env.GITHUB_SERVER_URL}/${process.env.GITHUB_REPOSITORY}/actions/runs/${process.env.GITHUB_RUN_ID}`
    : "";

const summary = buildRunSummary(workflowName, bundle, runUrl);

if (process.env.AGENTFORGE_REPORT_OUTPUT) {
  writeFileSync(process.env.AGENTFORGE_REPORT_OUTPUT, summary, "utf8");
}

if (process.env.GITHUB_STEP_SUMMARY) {
  writeFileSync(process.env.GITHUB_STEP_SUMMARY, `${summary}\n`, { flag: "a" });
}

const repo = requireEnv("GITHUB_REPOSITORY");

if (process.env.GITHUB_EVENT_NAME === "pull_request" && process.env.GITHUB_EVENT_PATH) {
  const event = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, "utf8"));
  const pullNumber = event.pull_request?.number;
  if (pullNumber) {
    upsertIssueComment(repo, pullNumber, "<!-- agentforge-pr-review -->", `<!-- agentforge-pr-review -->\n${summary}`);
  }
}

if (process.env.AGENTFORGE_TRACKER_ISSUE) {
  const trackerComment = buildTrackerComment(workflowName, bundle, runUrl);
  upsertIssueComment(
    repo,
    process.env.AGENTFORGE_TRACKER_ISSUE,
    "<!-- agentforge-tracker-update -->",
    `<!-- agentforge-tracker-update -->\n${trackerComment}`
  );
}
